#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import urllib.request

from import_official_vtt_transcript import REQUEST_HEADERS, ROOT, clean_filename


def parse_txt(content: str) -> list[dict[str, object]]:
    blocks = re.split(r"\n\s*\n", content.replace("\r\n", "\n").replace("\r", "\n"))
    segments: list[dict[str, object]] = []
    for block in blocks:
        lines = [line.strip() for line in block.splitlines() if line.strip()]
        if len(lines) < 2:
            continue
        speaker, *speech = lines
        text = " ".join(speech).strip()
        if text:
            segments.append({"start": None, "end": None, "timestamp": None, "speaker": speaker, "text": text})
    return segments


def main() -> None:
    parser = argparse.ArgumentParser(description="Import an official RSS plain-text transcript without inventing timestamps.")
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--index", type=int, required=True)
    parser.add_argument("--out-dir", type=Path, default=ROOT / "data" / "transcripts" / "spotify_en")
    args = parser.parse_args()

    manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
    episodes = manifest.get("new_episodes") or []
    if not 1 <= args.index <= len(episodes):
        raise SystemExit(f"Episode index {args.index} is outside 1..{len(episodes)}.")
    episode = episodes[args.index - 1]
    url = str(episode.get("transcript_url") or "")
    identity = str(episode.get("guid") or episode.get("episode_url") or "").strip()
    if not url.endswith("/transcript.txt") or not identity:
        raise SystemExit("Selected episode needs an official transcript.txt URL and stable RSS identity.")

    request = urllib.request.Request(url, headers={**REQUEST_HEADERS, "Accept": "text/plain,*/*;q=0.8"})
    with urllib.request.urlopen(request, timeout=120) as response:
        segments = parse_txt(response.read().decode("utf-8-sig"))
    if len(segments) < 20:
        raise SystemExit(f"Only {len(segments)} speech blocks parsed; refusing a likely partial transcript.")

    published_date = str(episode.get("published_at") or "")[:10]
    payload = {
        "source": "official_rss_txt",
        "sourceEpisodeId": identity,
        "episodeUrl": episode.get("episode_url"),
        "transcriptUrl": url,
        "podcastName": episode.get("podcast_title"),
        "episodeTitle": episode.get("episode_title"),
        "publishedDate": published_date,
        "duration": episode.get("duration"),
        "transcriptLanguage": "en",
        "isAutoGenerated": "unknown",
        "segments": segments,
        "debugLogs": ["Imported from official RSS plain-text transcript; source has no timestamps."],
    }
    filename = (
        f"{published_date} - {clean_filename(episode.get('podcast_title'))} - "
        f"{clean_filename(episode.get('episode_title'))} - rss-txt-{clean_filename(identity)}.json"
    )
    args.out_dir.mkdir(parents=True, exist_ok=True)
    output_path = args.out_dir / filename
    output_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"path={output_path}")
    print(f"segments={len(segments)}")


if __name__ == "__main__":
    main()
