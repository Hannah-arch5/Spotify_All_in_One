#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
from pathlib import Path

from import_official_vtt_transcript import ROOT, clean_filename, format_timestamp


DEFAULT_OUT_DIR = ROOT / "data" / "transcripts" / "spotify_en"


def parse_timestamp(value: object) -> float:
    parts = str(value or "00:00:00,000").replace(",", ".").split(":")
    if len(parts) != 3:
        raise ValueError(f"Unexpected timestamp: {value!r}")
    return int(parts[0]) * 3600 + int(parts[1]) * 60 + float(parts[2])


def parse_transcription(data: dict[str, object]) -> list[dict[str, object]]:
    segments: list[dict[str, object]] = []
    for item in data.get("transcription") or []:
        if not isinstance(item, dict):
            continue
        text = str(item.get("text") or "").strip()
        if not text:
            continue
        timestamps = item.get("timestamps") or {}
        offsets = item.get("offsets") or {}
        start = (
            float(offsets.get("from")) / 1000
            if offsets.get("from") is not None
            else parse_timestamp(timestamps.get("from"))
        )
        end = (
            float(offsets.get("to")) / 1000
            if offsets.get("to") is not None
            else parse_timestamp(timestamps.get("to"))
        )
        segments.append(
            {
                "start": start,
                "end": end,
                "timestamp": format_timestamp(start),
                "speaker": None,
                "text": text,
            }
        )
    return segments


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Import a verified public Castbox transcript without inventing Spotify identity."
    )
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--index", type=int, required=True)
    parser.add_argument("--transcript-file", type=Path, required=True)
    parser.add_argument("--castbox-eid", required=True)
    parser.add_argument("--transcript-url", required=True)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    args = parser.parse_args()

    manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
    episodes = manifest.get("new_episodes") or manifest.get("episodes") or []
    if not 1 <= args.index <= len(episodes):
        raise SystemExit(f"Episode index {args.index} is outside 1..{len(episodes)}.")
    episode = episodes[args.index - 1]

    raw = json.loads(args.transcript_file.read_text(encoding="utf-8"))
    language = str((raw.get("result") or {}).get("language") or "").lower()
    if not language.startswith("en"):
        raise SystemExit(f"Expected an English Castbox transcript, got language={language!r}.")
    segments = parse_transcription(raw)
    if len(segments) < 20:
        raise SystemExit(f"Only {len(segments)} segments parsed; refusing a likely partial transcript.")
    if any(segments[index]["start"] > segments[index + 1]["start"] for index in range(len(segments) - 1)):
        raise SystemExit("Transcript timestamps are not monotonic.")

    published_date = str(episode.get("published_at") or "")[:10]
    source_episode_id = f"castbox:{args.castbox_eid}"
    payload = {
        "source": "castbox_public_asr",
        "sourceEpisodeId": source_episode_id,
        "episodeUrl": episode.get("episode_url"),
        "transcriptUrl": args.transcript_url,
        "podcastName": episode.get("podcast_title"),
        "episodeTitle": episode.get("episode_title"),
        "publishedDate": published_date,
        "duration": episode.get("duration"),
        "transcriptLanguage": language,
        "isAutoGenerated": True,
        "segments": segments,
        "debugLogs": [
            "Imported from the verified public Castbox episode transcript endpoint.",
            "Spotify exposed no native Transcript tab after the required detail-page wait.",
        ],
    }
    filename = (
        f"{published_date} - {clean_filename(episode.get('podcast_title'))} - "
        f"{clean_filename(episode.get('episode_title'))} - castbox-{clean_filename(args.castbox_eid)}.json"
    )
    args.out_dir.mkdir(parents=True, exist_ok=True)
    output_path = args.out_dir / filename
    output_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"path={output_path}")
    print(f"source_episode_id={source_episode_id}")
    print(f"segments={len(segments)}")


if __name__ == "__main__":
    main()
