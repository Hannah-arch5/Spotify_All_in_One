#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re

import pdfplumber

from import_official_vtt_transcript import DEFAULT_OUT_DIR, clean_filename


SPEAKER_RE = re.compile(r"(?m)^(Allison Nathan|Chamath Palihapitiya|Eric Sheridan):\s*")


def parse_speaker_turns(pages: list[str]) -> list[dict[str, object]]:
    text = "\n".join(re.sub(r"(?m)^\d{1,2}$", "", page) for page in pages)
    matches = list(SPEAKER_RE.finditer(text))
    segments: list[dict[str, object]] = []
    for index, match in enumerate(matches):
        stop = matches[index + 1].start() if index + 1 < len(matches) else len(text)
        speech = re.sub(r"\s+", " ", text[match.end():stop]).strip()
        if speech:
            segments.append({"start": None, "end": None, "timestamp": None, "speaker": match.group(1), "text": speech})
    return segments


def main() -> None:
    parser = argparse.ArgumentParser(description="Import the publisher's official PDF transcript without invented timestamps.")
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--index", type=int, required=True)
    parser.add_argument("--pdf-file", type=Path, required=True)
    parser.add_argument("--source-url", required=True)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    args = parser.parse_args()
    episodes = json.loads(args.manifest.read_text(encoding="utf-8")).get("new_episodes") or []
    if not 1 <= args.index <= len(episodes):
        raise SystemExit("Episode index is outside the manifest.")
    episode = episodes[args.index - 1]
    if episode.get("podcast_title") != "Exchanges" or "goldmansachs.com/" not in args.source_url:
        raise SystemExit("This importer only accepts the official Goldman Sachs Exchanges transcript.")
    identity = str(episode.get("guid") or "").strip()
    if not identity:
        raise SystemExit("Official transcript needs the RSS episode GUID.")
    with pdfplumber.open(args.pdf_file) as pdf:
        pages = [page.extract_text() or "" for page in pdf.pages]
    title = str(episode.get("episode_title") or "").strip()
    if not pages or "What Will Determine the Durability of the AI" not in pages[0]:
        raise SystemExit("Official PDF title did not match the manifest; refusing import.")
    segments = parse_speaker_turns(pages)
    if len(segments) < 15:
        raise SystemExit(f"Only {len(segments)} speaker turns; refusing a likely partial transcript.")
    published_date = str(episode.get("published_at") or "")[:10]
    payload = {
        "source": "goldmansachs_official_transcript_pdf",
        "sourceEpisodeId": identity,
        "episodeUrl": episode.get("episode_url"),
        "transcriptUrl": args.source_url,
        "podcastName": episode.get("podcast_title"),
        "episodeTitle": title,
        "publishedDate": published_date,
        "duration": episode.get("duration"),
        "transcriptLanguage": "en",
        "isAutoGenerated": "unknown",
        "segments": segments,
        "debugLogs": ["Imported from the publisher's official PDF transcript; source has no timestamps."],
    }
    filename = f"{published_date} - Exchanges - {clean_filename(title)} - official-pdf-{clean_filename(identity)}.json"
    args.out_dir.mkdir(parents=True, exist_ok=True)
    path = args.out_dir / filename
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"path={path}")
    print(f"segments={len(segments)}")


if __name__ == "__main__":
    main()
