#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
from urllib.parse import parse_qs, urlparse

from import_official_vtt_transcript import ROOT, clean_filename


TIMESTAMP_RE = re.compile(r"^\[(?P<timestamp>\d{1,2}:\d{2}(?::\d{2})?)\]\s*(?P<text>.*)$")


def parse_time(value: str) -> float:
    parts = [int(part) for part in value.split(":")]
    if len(parts) == 2:
        return float(parts[0] * 60 + parts[1])
    return float(parts[0] * 3600 + parts[1] * 60 + parts[2])


def parse_transcript(content: str) -> list[dict[str, object]]:
    segments: list[dict[str, object]] = []
    current: dict[str, object] | None = None
    for raw_line in content.replace("\r\n", "\n").replace("\r", "\n").splitlines():
        line = raw_line.strip()
        match = TIMESTAMP_RE.match(line)
        if match:
            if current and current["text"]:
                segments.append(current)
            timestamp = match.group("timestamp")
            current = {
                "start": parse_time(timestamp),
                "end": None,
                "timestamp": timestamp,
                "speaker": None,
                "text": match.group("text").strip(),
            }
        elif current and line:
            current["text"] = f"{current['text']} {line}".strip()
    if current and current["text"]:
        segments.append(current)
    for index, segment in enumerate(segments[:-1]):
        segment["end"] = segments[index + 1]["start"]
    return segments


def youtube_id(url: str) -> str | None:
    parsed = urlparse(url)
    if parsed.hostname in {"youtu.be", "www.youtu.be"}:
        return parsed.path.strip("/") or None
    if parsed.hostname and parsed.hostname.endswith("youtube.com"):
        return parse_qs(parsed.query).get("v", [None])[0]
    return None


def main() -> None:
    parser = argparse.ArgumentParser(description="Import an exported official YouTube transcript text file.")
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--index", type=int, required=True)
    parser.add_argument("--transcript-file", type=Path, required=True)
    parser.add_argument(
        "--source-url",
        help="Verified YouTube watch URL when the manifest episode URL points elsewhere.",
    )
    parser.add_argument("--out-dir", type=Path, default=ROOT / "data" / "transcripts" / "spotify_en")
    args = parser.parse_args()

    manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
    episodes = manifest.get("new_episodes") or manifest.get("episodes") or []
    if not 1 <= args.index <= len(episodes):
        raise SystemExit(f"Episode index {args.index} is outside 1..{len(episodes)}.")
    episode = episodes[args.index - 1]
    episode_url = str(episode.get("episode_url") or "")
    transcript_url = str(args.source_url or episode_url)
    video_id = youtube_id(transcript_url)
    if not video_id:
        raise SystemExit("Selected manifest episode does not have a verifiable YouTube video URL.")

    content = args.transcript_file.read_text(encoding="utf-8-sig")
    declared_id = re.search(r"^Video ID:\s*(\S+)\s*$", content, re.MULTILINE)
    if declared_id and declared_id.group(1) != video_id:
        raise SystemExit(f"Transcript video ID {declared_id.group(1)} does not match manifest {video_id}.")
    segments = parse_transcript(content)
    if len(segments) < 20:
        raise SystemExit(f"Only {len(segments)} timestamped lines parsed; refusing a likely partial transcript.")

    published_date = str(episode.get("published_at") or "")[:10]
    source_episode_id = f"youtube:{video_id}"
    payload = {
        "source": "official_youtube_transcript",
        "sourceEpisodeId": source_episode_id,
        "episodeUrl": episode_url,
        "transcriptUrl": transcript_url,
        "podcastName": episode.get("podcast_title"),
        "episodeTitle": episode.get("episode_title"),
        "publishedDate": published_date,
        "duration": episode.get("duration"),
        "transcriptLanguage": "en",
        "isAutoGenerated": "auto-generated" in content[:300].lower(),
        "segments": segments,
        "debugLogs": ["Imported from the official YouTube page transcript export."],
    }
    filename = (
        f"{published_date} - {clean_filename(episode.get('podcast_title'))} - "
        f"{clean_filename(episode.get('episode_title'))} - youtube-{video_id}.json"
    )
    args.out_dir.mkdir(parents=True, exist_ok=True)
    output_path = args.out_dir / filename
    output_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"path={output_path}")
    print(f"source_episode_id={source_episode_id} segments={len(segments)}")


if __name__ == "__main__":
    main()
