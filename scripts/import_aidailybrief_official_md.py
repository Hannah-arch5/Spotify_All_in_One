#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import urllib.request

from import_official_vtt_transcript import DEFAULT_OUT_DIR, REQUEST_HEADERS, clean_filename, parse_time


STAMP_RE = re.compile(r"\[(\d{2}:\d{2}:\d{2})\]")


def parse_markdown(content: str) -> list[dict[str, object]]:
    body = content.split("\n---\n", 1)[-1]
    pieces = STAMP_RE.split(body)
    segments: list[dict[str, object]] = []
    for stamp, speech in zip(pieces[1::2], pieces[2::2]):
        text = re.sub(r"\s+", " ", speech).strip()
        if text:
            segments.append(
                {"start": parse_time(stamp), "end": None, "timestamp": stamp, "speaker": None, "text": text}
            )
    return segments


def main() -> None:
    parser = argparse.ArgumentParser(description="Import The AI Daily Brief's official transcript Markdown.")
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--index", type=int, required=True)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    args = parser.parse_args()

    episodes = json.loads(args.manifest.read_text(encoding="utf-8")).get("new_episodes") or []
    if not 1 <= args.index <= len(episodes):
        raise SystemExit("Episode index is outside the manifest.")
    episode = episodes[args.index - 1]
    if episode.get("podcast_title") != "The AI Daily Brief":
        raise SystemExit("Selected episode is not The AI Daily Brief.")
    identity = str(episode.get("guid") or "").strip()
    if not identity:
        raise SystemExit("Official transcript needs the RSS episode GUID.")
    published_date = str(episode.get("published_at") or "")[:10]
    url = f"https://www.aidailybrief.ai/e/{published_date}/transcript.md"
    request = urllib.request.Request(url, headers={**REQUEST_HEADERS, "Accept": "text/markdown,*/*;q=0.8"})
    with urllib.request.urlopen(request, timeout=120) as response:
        content = response.read().decode("utf-8-sig")
    title = str(episode.get("episode_title") or "").strip()
    if not content.startswith(f"# {title} — Transcript ({published_date})"):
        raise SystemExit("Official transcript title/date did not match the manifest; refusing import.")
    segments = parse_markdown(content)
    if len(segments) < 10:
        raise SystemExit(f"Only {len(segments)} timestamped segments; refusing a likely partial transcript.")
    payload = {
        "source": "aidailybrief_official_transcript_md",
        "sourceEpisodeId": identity,
        "episodeUrl": episode.get("episode_url"),
        "transcriptUrl": url,
        "podcastName": episode.get("podcast_title"),
        "episodeTitle": title,
        "publishedDate": published_date,
        "duration": episode.get("duration"),
        "transcriptLanguage": "en",
        "isAutoGenerated": "unknown",
        "segments": segments,
        "debugLogs": ["Imported from the publisher's official dated transcript Markdown."],
    }
    filename = f"{published_date} - The AI Daily Brief - {clean_filename(title)} - official-md-{clean_filename(identity)}.json"
    args.out_dir.mkdir(parents=True, exist_ok=True)
    path = args.out_dir / filename
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"path={path}")
    print(f"segments={len(segments)}")


if __name__ == "__main__":
    main()
