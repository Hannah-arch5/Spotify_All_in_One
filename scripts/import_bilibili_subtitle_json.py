#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT_DIR = ROOT / "data" / "transcripts" / "spotify_en"


def clean_filename(value: object) -> str:
    return re.sub(r'[\\/:*?"<>|#%]', "_", str(value or "unknown")).strip()


def format_timestamp(value: object) -> str:
    seconds = max(0, int(float(value or 0)))
    hours, remainder = divmod(seconds, 3600)
    minutes, secs = divmod(remainder, 60)
    if hours:
        return f"{hours}:{minutes:02d}:{secs:02d}"
    return f"{minutes}:{secs:02d}"


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Import a verified official Bilibili subtitle JSON into the original transcript archive."
    )
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--index", type=int, required=True, help="One-based episode index in the manifest.")
    parser.add_argument("--bvid", required=True)
    parser.add_argument("--subtitle-file", type=Path, required=True)
    parser.add_argument("--subtitle-url")
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    args = parser.parse_args()

    manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
    episodes = manifest.get("new_episodes") or manifest.get("episodes") or []
    if args.index < 1 or args.index > len(episodes):
        raise SystemExit(f"Episode index {args.index} is outside 1..{len(episodes)}.")
    episode = episodes[args.index - 1]

    subtitle = json.loads(args.subtitle_file.read_text(encoding="utf-8"))
    body = subtitle.get("body")
    if not isinstance(body, list) or not body:
        raise SystemExit("Bilibili subtitle JSON contains no body rows.")

    segments = []
    for row in body:
        if not isinstance(row, dict):
            continue
        text = str(row.get("content") or "").strip()
        if not text:
            continue
        start = float(row.get("from") or 0)
        end = float(row.get("to") or start)
        segments.append(
            {
                "start": start,
                "end": end,
                "timestamp": format_timestamp(start),
                "speaker": episode.get("podcast_title"),
                "text": text,
            }
        )
    if not segments:
        raise SystemExit("Bilibili subtitle JSON contains no non-empty subtitle rows.")

    published_date = str(episode.get("published_at") or "")[:10]
    source_episode_id = f"bilibili:{args.bvid}"
    video_url = f"https://www.bilibili.com/video/{args.bvid}/"
    payload = {
        "source": "bilibili_official_ai_subtitle",
        "sourceEpisodeId": source_episode_id,
        "episodeUrl": video_url,
        "originalEpisodeUrl": episode.get("episode_url"),
        "transcriptUrl": args.subtitle_url,
        "podcastName": episode.get("podcast_title"),
        "episodeTitle": episode.get("episode_title"),
        "publishedDate": published_date,
        "duration": segments[-1]["end"],
        "transcriptLanguage": subtitle.get("lang") or "zh-CN",
        "isAutoGenerated": True,
        "segments": segments,
        "debugLogs": ["Imported from a verified official Bilibili AI subtitle JSON."],
    }

    filename = (
        f"{published_date} - {clean_filename(episode.get('podcast_title'))} - "
        f"{clean_filename(episode.get('episode_title'))} - bilibili-{args.bvid}.json"
    )
    args.out_dir.mkdir(parents=True, exist_ok=True)
    output_path = args.out_dir / filename
    output_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"path={output_path}")
    print(f"source_episode_id={source_episode_id}")
    print(f"segments={len(segments)}")


if __name__ == "__main__":
    main()
